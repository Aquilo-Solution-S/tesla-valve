"""Draws the pictures in MANIFESTO.md: tesla-valve.svg and streams.svg.

    python3 assets/draw.py

Both share one palette, so they always match.
"""

import math
from pathlib import Path

STYLE = """\
    :root { --paper: #f7f5f0; --ink: #1f2d3a; --water: #dbeaf4; --flow: #2a7fc0; --note: #6b7785; }
    @media (prefers-color-scheme: dark) {
      :root { --paper: #0e1720; --ink: #8fb0cc; --water: #14293c; --flow: #7cc8ff; --note: #7d8fa1; }
    }
    .plate { fill: var(--paper); stroke: var(--ink); stroke-width: 2; }
    .hole  { fill: none; stroke: var(--ink); stroke-width: 1.2; }
    .wall  { fill: none; stroke: var(--ink); }
    .bank  { fill: none; stroke: var(--paper); }
    .water { fill: none; stroke: var(--water); }
    .part  { fill: var(--paper); stroke: var(--ink); stroke-width: 1.4; }
    .pool  { fill: var(--water); stroke: var(--ink); stroke-width: 1.4; }
    .drop  { fill: var(--flow); }
    .flow  { fill: none; stroke: var(--flow); stroke-linecap: round; stroke-dasharray: 0 16; animation: flow 1.2s linear infinite; }
    .place { fill: var(--ink); font: 13px -apple-system, BlinkMacSystemFont, "Segoe UI", Helvetica, Arial, sans-serif; }
    .code  { fill: var(--ink); font: 13px ui-monospace, SFMono-Regular, Menlo, Consolas, monospace; }
    .type  { fill: var(--flow); font: 600 13px ui-monospace, SFMono-Regular, Menlo, Consolas, monospace; }
    .refused { fill: none; stroke: var(--note); stroke-width: 1.4; stroke-dasharray: 3 3; }
    .back  { fill: var(--note); }
    .note  { fill: var(--note); font: italic 11.5px -apple-system, BlinkMacSystemFont, "Segoe UI", Helvetica, Arial, sans-serif; }
    @keyframes flow { to { stroke-dashoffset: -32; } }
    @media (prefers-reduced-motion: reduce) { .flow { animation: none; } }"""

WIDTH = 9     # channel
WALL = 1.4
HEADER = "<!-- Generated by draw.py. Edit that and run it. -->"


def num(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


def valve():
    """Tesla's geometry (US patent 1,329,559). The channel zigzags, and at
    every corner it also carries straight on into a loop: the circle that
    touches both channel lines there. Flow from the left takes the corner.
    Flow from the right runs straight into the loop, wraps the island and
    comes back out against itself."""
    step = 150     # horizontal distance between corners
    rise = 21.5    # corners sit this far above and below the centre line
    loop = 20      # radius of the loop around each island
    corners = 5
    margin = 30    # plate beyond the ports
    pad = 26       # plate beyond the loops

    slope = math.atan2(2 * rise, step)
    # The loop's centre lies on the corner's bisector, where the circle
    # touches both channel lines; (tx, ty) is where it touches them.
    centre = loop / math.sin(slope)
    tx, ty = centre * math.cos(slope) ** 2, centre * math.cos(slope) * math.sin(slope)
    cell = f"M0,0 L{num(-tx)},{num(ty)} A{loop},{loop} 0 1 1 {num(-tx)},{num(-ty)}"

    # One extra corner on each side, without a loop, leads to the ports.
    xs = [i * step for i in range(-1, corners + 1)]
    ys = [rise if i % 2 else -rise for i in range(-1, corners + 1)]

    left, right = xs[0] - margin, xs[-1] + margin
    outer = rise + loop + WIDTH / 2 + WALL
    half = math.ceil(outer + pad)
    hole = (outer + half) / 2
    line = " L".join(f"{num(x)},{num(y)}" for x, y in zip(xs, ys))
    main = f"M{num(left - 20)},{num(ys[0])} L{line} L{num(right + 20)},{num(ys[-1])}"
    cells = "\n".join(
        f'      <use href="#cell" transform="translate({num(x)} {num(y)}){" scale(1 -1)" if y < 0 else ""}"/>'
        for x, y in zip(xs[1:-1], ys[1:-1])
    )
    holes = "\n".join(
        f'    <circle class="hole" cx="{num(x)}" cy="{num(y)}" r="3.2"/>' for x in xs for y in (-hole, hole)
    )
    plate = f'x="{num(left)}" y="{-half}" width="{num(right - left)}" height="{2 * half}" rx="14"'

    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="{num(left)} {-half} {num(right - left)} {2 * half}" width="{num(right - left)}" height="{2 * half}" role="img" aria-label="A Tesla valve. Water flows freely from left to right. Flowing back, every loop turns it against itself.">
  {HEADER}
  <style>
{STYLE}
  </style>
  <defs>
    <!-- One corner: the channel carries straight on, wraps the island and
         rejoins pointing backwards. Every second corner is this cell, mirrored. -->
    <path id="cell" d="{cell}"/>
    <g id="valve" stroke-linecap="round" stroke-linejoin="round">
      <path id="main" d="{main}"/>
{cells}
    </g>
    <clipPath id="edge"><rect {plate}/></clipPath>
  </defs>
  <g clip-path="url(#edge)">
    <rect class="plate" {plate}/>
{holes}
    <use href="#valve" class="wall" stroke-width="{num(WIDTH + 2 * WALL)}"/>
    <use href="#valve" class="water" stroke-width="{WIDTH}"/>
    <use href="#main" class="flow" stroke-width="{num(WIDTH * 0.26)}"/>
  </g>
</svg>
"""


def streams():
    """One feature traced from its springs to its goal: show the delivery date
    at checkout. A double wall marks a stream that already flows."""
    a, b, c = 80, 165, 250  # postcode, stock, today
    spring, gate, canal_end, bend, meet, goal = 60, 240, 460, 570, 700, 890
    postcode = f"M{spring},{a} H{bend} C{bend + 70},{a} {bend + 70},{b} {meet},{b}"
    stock = f"M{spring},{b} H{meet}"
    today = f"M{spring},{c} H{bend} C{bend + 70},{c} {bend + 70},{b} {meet},{b}"
    out = f"M{meet},{b} H{goal - 13}"
    canal = f"M{spring},{b} H{canal_end}"
    refused = f"M{gate},{a + 13} C{gate},{a + 26} {gate - 6},{a + 30} {gate - 18},{a + 30}"
    sw = num(WIDTH + 2 * WALL)
    streams = f'<path d="{postcode}"/><path d="{stock}"/><path d="{today}"/><path d="{out}"/>'

    def spring_at(y, place):
        return (
            f'<circle class="pool" cx="{spring}" cy="{y}" r="8"/><circle class="drop" cx="{spring}" cy="{y}" r="2.5"/>\n'
            f'  <text class="place" x="{spring}" y="{y - 18}" text-anchor="middle">{place}</text>\n'
            f'  <text class="note" x="{spring}" y="{y + 27}" text-anchor="middle">outside</text>'
        )

    def gate_at(y):
        return f'<rect class="part" x="{gate - 4}" y="{y - 13}" width="8" height="26" rx="2"/>'

    def kind(x, y, name):
        return f'<text class="type" x="{x}" y="{y + 25}" text-anchor="middle">{name}</text>'

    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 960 300" width="960" height="300" role="img" aria-label="Three streams for one feature. A postcode from the checkout form is checked once and becomes a Postcode; what fails the check goes back to the form. The warehouse's stock already flows through stock_of and is joined, not dug again. The clock gives today's date. All three meet in delivery_date, which gives the checkout a Date.">
  {HEADER}
  <style>
{STYLE}
  </style>
  <defs>
    <marker id="head" viewBox="0 0 6 6" refX="3" refY="3" markerWidth="6" markerHeight="6" orient="auto">
      <path class="back" d="M0,0 L6,3 L0,6 z"/>
    </marker>
  </defs>
  <rect class="plate" x="1" y="1" width="958" height="298" rx="14"/>

  <!-- channels: the canal's double wall first, then every wall, then the water -->
  <path class="wall" d="{canal}" stroke-width="{num(WIDTH + 2 * WALL + 6)}"/>
  <path class="bank" d="{canal}" stroke-width="{num(WIDTH + 2 * WALL + 3.2)}"/>
  <g class="wall" stroke-width="{sw}" stroke-linecap="round">{streams}</g>
  <g class="water" stroke-width="{WIDTH}" stroke-linecap="round">{streams}</g>
  <g class="flow" stroke-width="{num(WIDTH * 0.26)}">{streams}</g>

  <!-- springs and their checks; what a check refuses goes back -->
  {spring_at(a, "checkout form")}
  {gate_at(a)}
  <text class="code" x="{gate}" y="{a - 18}" text-anchor="middle">Postcode::parse</text>
  <path class="refused" d="{refused}" marker-end="url(#head)"/>
  <text class="note" x="{gate - 26}" y="{a + 34}" text-anchor="end">Invalid</text>
  {kind((spring + gate) // 2 - 10, a, "text")}
  {kind((gate + bend) // 2, a, "Postcode")}

  {spring_at(b, "warehouse")}
  {gate_at(b)}
  <text x="{gate}" y="{b - 18}" text-anchor="middle"><tspan class="code">stock_of</tspan><tspan class="note"> · already flows</tspan></text>
  {kind((spring + gate) // 2 - 10, b, "JSON")}
  {kind((gate + bend) // 2, b, "Stock")}

  {spring_at(c, "clock")}
  {kind((spring + bend) // 2, c, "Date")}

  <!-- where they meet, and the goal -->
  <circle class="part" cx="{meet}" cy="{b}" r="7"/>
  <text x="{meet + 14}" y="{b - 14}"><tspan class="code">delivery_date</tspan><tspan class="note"> · new</tspan></text>
  {kind((meet + goal) // 2, b, "Date")}
  <circle class="pool" cx="{goal}" cy="{b}" r="13"/><circle class="drop" cx="{goal}" cy="{b}" r="4.5"/>
  <text class="place" x="{goal}" y="{b - 24}" text-anchor="middle">checkout</text>
  <text class="note" x="{goal}" y="{b + 32}" text-anchor="middle">“Arrives Thursday”</text>
</svg>
"""


here = Path(__file__).parent
(here / "tesla-valve.svg").write_text(valve())
(here / "streams.svg").write_text(streams())
